uint16_t battery_vdd_min_mv(void) { return vdd_min; }
uint16_t battery_vdd_max_mv(void) { return vdd_max; }

/* --- Supply: what powers the rail ---------------------------------------------
 * A state machine, not a threshold. The old predicate (VDD < 4300 mV) flickered
 * as VDD crept through 4300 in the charge taper, and called a pack charging
 * hard at VDD 4193 mV "on battery" for four hours (2026-09-28).
 *
 *   CHRG low on 2 consecutive ticks   -> EXTERNAL evidence, held 1 s past the
 *                                        last low (covers the charger's ~2 Hz
 *                                        no-pack pulse). CHRG can only sink
 *                                        with USB present: a direct observation.
 *   raw VDD >= 4100 mV for 0.5 s      -> EXTERNAL
 *   raw VDD <  4000 mV for 1 s,
 *     with no EXTERNAL evidence       -> BATTERY
 *   otherwise                         -> keep the previous state
 *
 * On battery VDD is ~3.90 V; on USB no raw sample went under 4119 mV across a
 * 7.5 h charge into a dead pack. ⚠️ The ADC reference is +-2% per part:
 * re-check both margins on another unit. */
#define EXT_ENTER_MV       4100u
#define BATT_ENTER_MV      4000u
#define EXT_ENTER_TICKS    5u
#define BATT_ENTER_TICKS   10u
#define CHRG_QUALIFY_TICKS 2u
#define CHRG_HOLD_TICKS    10u
/* Unbroken charging this long is a real charging session: the level may rise,
 * and a brief plug-in cannot bump it. */
#define SESSION_TICKS      600u    /* 60 s */
/* CHRG released this long, on USB, with `5C` at 100: the charger terminated. */
#define FULL_SETTLE_TICKS  100u    /* 10 s */
/* A second of failed conversions and what VDD last said has expired. */
#define ADC_STALE_TICKS    10u

static battery_supply_t supply        = BATTERY_SUPPLY_UNKNOWN;
static uint8_t          ext_run       = 0;   /* raw VDD >= EXT_ENTER_MV, ticks */
static uint8_t          batt_run      = 0;   /* raw VDD <  BATT_ENTER_MV, ticks */
static uint16_t         chrg_run      = 0;   /* CHRG low, consecutive ticks */
static uint16_t         chrg_off_run  = 0;   /* CHRG high, consecutive ticks */
static uint8_t          chrg_hold     = 0;   /* ticks of EXTERNAL evidence left */
static uint8_t          adc_fail_run  = 0;   /* consecutive failed conversions */
/* Consecutive ticks with FRESH positive evidence of USB -- CHRG, or VDD read
 * this second. Not "supply is EXTERNAL": that is remembered, and a remembered
 * state must never be what lifts the low-battery cut (codex, 2026-09-28). */
static uint16_t         ext_evidence_ticks = 0;
static bool             chg_was       = false;   /* charging_now() last tick */
static bool             session       = false;
static uint16_t         session_count = 0;   /* real charging sessions this boot (power.c's re-arm) */
static bool             ran_from_pack = false;
/* Set when the board goes onto the pack after a real charging session: the
 * level re-seats once, from the first post-unplug estimate (see level_report).
 * Owed until consumed: a brief replug before the estimate exists must not cancel
 * it, or the discharge keeps the charging estimate and its guessed I*R. */
static bool             reseat        = false;

static void c5_forget(void);
static void supply_changed(battery_supply_t was);
static void boot_first_latch(uint16_t est);

static bool charging_now(void) {
    return supply == BATTERY_SUPPLY_EXTERNAL && chrg_hold != 0;
}

/* Conversions that read, since boot (wrapping): a deep sleep's recovery waits
 * for 1.5 s of them after the wake before it lets the board sleep again. */
static uint16_t supply_samples = 0;

uint16_t battery_supply_samples(void) {
    return supply_samples;
}

static void supply_tick(uint16_t raw_mv) {
    bool chrg_low = !gpio_read_pin(CHARGE_CHRG_PIN);
    if (chrg_low) {
        if (chrg_run < UINT16_MAX) chrg_run++;
        chrg_off_run = 0;
    } else {
        chrg_run = 0;
        if (chrg_off_run < UINT16_MAX) chrg_off_run++;
    }
    if (chrg_run >= CHRG_QUALIFY_TICKS) {
        chrg_hold = CHRG_HOLD_TICKS;
    } else if (chrg_hold) {
        chrg_hold--;
    }

    /* A failed conversion is no information: the runs hold rather than reset.
     * A second of them and the runs expire -- the supply then holds (only CHRG
     * can still move it), but nothing counts as fresh proof of USB. */
    if (raw_mv) {
        supply_samples++;
        adc_fail_run = 0;
        ext_run  = (raw_mv >= EXT_ENTER_MV)  ? (uint8_t)(ext_run  < UINT8_MAX ? ext_run  + 1u : ext_run)  : 0u;
        batt_run = (raw_mv <  BATT_ENTER_MV) ? (uint8_t)(batt_run < UINT8_MAX ? batt_run + 1u : batt_run) : 0u;
    } else if (adc_fail_run < UINT8_MAX && ++adc_fail_run >= ADC_STALE_TICKS) {
        ext_run = batt_run = 0;
    }

    bool ext_evidence  = chrg_hold || ext_run >= EXT_ENTER_TICKS;
    ext_evidence_ticks = ext_evidence ? (uint16_t)(ext_evidence_ticks < UINT16_MAX ? ext_evidence_ticks + 1u : ext_evidence_ticks) : 0u;

    battery_supply_t was = supply;
    if (ext_evidence) {
        supply = BATTERY_SUPPLY_EXTERNAL;
    } else if (batt_run >= BATT_ENTER_TICKS) {
        supply = BATTERY_SUPPLY_BATTERY;
    }

    if (supply != was) {
        /* Every report in the estimate was taken on the other supply -- under
         * charge current, or without it -- so none describes this one. */
        c5_forget();
        supply_changed(was);
    }
    /* The charger starting or stopping moves the terminal voltage by I*R as
     * surely as a supply change does: a charger fault mid-charge must not be
     * judged FULL on reports taken while it was still charging. */
    bool chg = charging_now();
    if (chg != chg_was) {
        c5_forget();
        chg_was = chg;
    }
    if (supply == BATTERY_SUPPLY_BATTERY) {
        ran_from_pack = true;
        session       = false;
    }
    if (chrg_run >= SESSION_TICKS && !session) {
        session = true;
        session_count++;
    }
}

uint16_t battery_session_count(void) { return session_count; }
battery_supply_t battery_supply(void) { return supply; }
bool battery_on_battery(void)         { return supply == BATTERY_SUPPLY_BATTERY; }
bool battery_ran_from_pack(void)      { return ran_from_pack; }

/* --- `5C`: intake, freshness, the estimate -------------------------------------
 * The CH582F driver hands over every report as it is parsed
 * (battery_5c_report), so two that land between ticks are both counted -- in
 * the estimate, the critical-zero run, and the log. Never re-read the cached
 * value instead: that only duplicates the one report it holds.
 *
 * The estimate is a TRIMMED MEAN of the last 64 reports, in hundredths of a
 * count, dropping the highest and lowest eighth: ~2-2.5 min at the 262-334
 * reports per 10 min the v4 log counts. They come 2-3 per 5 s A6 53 poll cycle,
 * bunched (the debug page's age resets every ~5 s), so 64 reports may be only
 * ~25 independent readings; how the module produces them is unconfirmed
 * (docs/battery.md). Not a median: a median of whole counts is a whole count, and one count
 * is ~9 mV -- 1.2% of level at 4.0 V, up to ~5% near 3.8 V -- so the level moved
 * in lumps and then sat still for an hour. `5C` dithers between neighbouring
 * counts (the drain log's means read like 96.62), so a mean resolves about a
 * tenth of a count; the trim keeps the median's indifference to a stray report.
 *
 * Emptied when the reports go stale, so a module that falls silent and returns
 * is not judged on minutes-old values, and at every supply or charger change. */
#define C5_RING        64u
#define C5_MIN_EST     5u
#define C5_STALE_MS    20000u    /* ~8 missed reports */
#define C5_NONE        0xFFu
#define C5_EST_NONE    0xFFFFu
/* The clamps, as the estimate sees them: most reports at 100 (>= 4036 mV, the
 * voltage says only "at least"), or most at 0 (<= 3161 mV). */
#define C5_TOP_X100    9950u
#define C5_BOTTOM_X100 50u

static uint8_t  c5_ring[C5_RING];
static uint8_t  c5_count    = 0;
static uint8_t  c5_pos      = 0;
/* How many of the ring's c5_count reports hold each value 0..100: the trimmed
 * mean's sorted order without sorting (see c5_trimmed_mean_x100). Kept in step
 * with the ring on every insert, eviction and forget. */
static uint8_t  c5_hist[101];
static bool     c5_new      = false;         /* a report arrived since the last tick */
static uint16_t c5_est      = C5_EST_NONE;   /* hundredths of a count */
static uint8_t  c5_zero_run = 0;             /* consecutive reports of 0 */

/* The log's view of every report in the period (see log_task). The extrema
 * take every accepted report; only the sum and count saturate, and say so. */
static uint16_t lg_c5_sum = 0, lg_c5_n = 0;
static uint8_t  lg_c5_min = C5_NONE, lg_c5_max = 0;
static bool     lg_c5_saturated = false;

/* The estimate counts c5_ring[0 .. c5_count-1] through c5_hist, so the ring,
 * its write position and the counts restart together: resuming at the old
 * c5_pos would evict forgotten reports' counts that are no longer there. */
static void c5_forget(void) {
    c5_count    = 0;
    c5_pos      = 0;
    memset(c5_hist, 0, sizeof(c5_hist));
    c5_est      = C5_EST_NONE;
    c5_zero_run = 0;
}

static bool c5_fresh(void) {
    uint32_t age = ch582_battery_age_ms();
    return age != UINT32_MAX && age < C5_STALE_MS;
}

static bool c5_top(uint16_t e)    { return e != C5_EST_NONE && e >= C5_TOP_X100; }
static bool c5_bottom(uint16_t e) { return e < C5_BOTTOM_X100; }

/* The mean of the middle three quarters of the ring's reports (an eighth
 * trimmed from each end), in hundredths of a count.
 *
 * ⚠️ BY COUNTING, NOT SORTING (Phase 1b, D). It used to insertion-sort a copy of
 * the ring on every report: ~1.75 ms of wall time each on the board (mean,
 * worst 3.6 ms), and the module answers each 5 s battery poll with three
 * reports at once -- ~6 ms of one main-loop pass, which is what made the
 * battery-only >= 10 ms stalls (flash 1c's profile, 2026-10-07: 73.5% of the
 * slow CH582F calls' time). On USB at the clamp every report is 100 and the
 * sort moved nothing, which is why it was battery-only. Walking c5_hist from
 * 0 upward -- skip the lowest `trim` reports, sum the next `n` -- is the same
 * sum over the same sorted order, so the same result to the bit
 * (scripts/battery_sim, c5_equivalence, against the sort verbatim). */
static uint16_t c5_trimmed_mean_x100(void) {
    uint8_t  trim = (uint8_t)(c5_count / 8u);
    uint8_t  n    = (uint8_t)(c5_count - 2u * trim);
    uint8_t  skip = trim, keep = n;
    uint16_t sum  = 0;
    for (uint8_t v = 0; v <= 100u && keep; v++) {
        uint8_t c = c5_hist[v];
        if (!c) continue;
        if (skip) {
            uint8_t k = c < skip ? c : skip;
            skip = (uint8_t)(skip - k);
            c    = (uint8_t)(c - k);
        }
        uint8_t t = c < keep ? c : keep;
        sum  = (uint16_t)(sum + (uint16_t)t * v);
        keep = (uint8_t)(keep - t);
    }
    return (uint16_t)(((uint32_t)sum * 100u + n / 2u) / n);
}

/* Called by the CH582F driver for every `5C` frame it parses (main loop). */
void battery_5c_report(uint8_t v) {
    if (v > 100u) return;
    c5_new          = true;
    if (c5_count == C5_RING) c5_hist[c5_ring[c5_pos]]--;   /* the oldest report leaves */
    c5_ring[c5_pos] = v;
    c5_hist[v]++;
    c5_pos          = (uint8_t)((c5_pos + 1u) % C5_RING);
    if (c5_count < C5_RING) c5_count++;
    c5_est      = (c5_count >= C5_MIN_EST) ? c5_trimmed_mean_x100() : C5_EST_NONE;
    c5_zero_run = (v == 0u) ? (uint8_t)(c5_zero_run < UINT8_MAX ? c5_zero_run + 1u : c5_zero_run) : 0u;
    /* FROM-FLAT's input is the FIRST estimate: exactly five reports. The
     * module answers each poll with three at once, so the next task can
     * already see a sixth (codex, gate 7: 10,10,10 then 10,10,11 is 10.00
     * at five, 10.17 at six). */
    if (c5_count == C5_MIN_EST) boot_first_latch(c5_est);

    /* v5: the extrema follow every report. They used to update only while the
     * 16-bit sum accepted one, so after ~661 reports of 99 a later 100 reached
     * the estimator but not the log (codex, plan round 6). */
    if (v < lg_c5_min) lg_c5_min = v;
    if (v > lg_c5_max) lg_c5_max = v;
    if (!lg_c5_saturated && lg_c5_n < UINT16_MAX && lg_c5_sum <= (uint16_t)(UINT16_MAX - v)) {
        lg_c5_sum += v;
        lg_c5_n++;
    } else {
        lg_c5_saturated = true;   /* c5_mean and c5_n cover the reports before this, and
                                   * no later one: a smaller report after a rejected one
                                   * would break the prefix (codex, gate 7) */
    }
}

uint16_t battery_5c_x100(void) {
    return c5_fresh() ? c5_est : C5_EST_NONE;
}

uint8_t battery_5c_rounded(void) {
    uint16_t e = battery_5c_x100();
    return (e == C5_EST_NONE) ? C5_NONE : (uint8_t)((e + 50u) / 100u);
}

/* --- `5C` -> pack millivolts ---------------------------------------------------
 * mV = (5C + 361.04) / 114.22 * 1000, integer, from the estimate in hundredths.
 * ⚠️ Valid below the clamps. At them it returns roughly the clamp's BOUND
 * (3161, 4036): "at most" and "at least", which the callers treat as such --
 * never as a reading, never on the curve. */
#define FIT_SLOPE_X100  11422u      /* 114.22 counts per volt */
#define FIT_OFFSET_X100 36104u      /* 361.04 counts */

static uint16_t c5_to_mv(uint16_t x100) {
    return (uint16_t)((((uint32_t)x100 + FIT_OFFSET_X100) * 1000u + FIT_SLOPE_X100 / 2u) / FIT_SLOPE_X100);
}

uint16_t battery_pack_mv(void) {
    uint16_t e = battery_5c_x100();
    return (e == C5_EST_NONE) ? 0u : c5_to_mv(e);
}

/* --- The level ------------------------------------------------------------------
 * What the number means: the fraction of RUNTIME left at the kind of load the
 * curve was measured at. Behind a buck-boost the board draws constant power, so
 * that -- not charge -- is what a timed run calibrates, and it is what a user
 * wants to know.
 *
 * FITTED from JD's unit on TWO drain tests at full white, 2026-09-28 (51.6
 * equivalent full-white hours from FULL to the cut) and 2026-10-02 (50.4 h),
 * by scripts/battery_fit.py --refit (history/battery-2026-10-01-drain/
 * refit-output.txt). Each knot is the mean of the two runs' smoothed voltages
 * at that fraction of runtime. 0% is the RGB cut at 3400 mV (JD, 2026-10-01);
 * the top knot keeps LEVEL_CLAMP_EXIT's 90% (the clamp's exit fell at 89.6%
 * and 90.3%). Leave-one-out, each run's own curve scored on the other: below
 * 3.95 V within 0.54-0.59 points rms (worst 2.1); on the 3.95-4.036 V plateau
 * 3.1-3.2 rms, worst 8.9 -- inside the plan's thresholds, with little room.
 * ⚠️ The plateau holds ~20% of the runtime in ~20 mV: a few mV there (lighter
 * load, less sag, one run's pack a little different) is ~10%, and 2 mV of
 * estimator offset moves the worst error to ~10. Two runs of one pack at one
 * load: a consistency check, not a confidence bound. The one-run curve this
 * replaces (759e265796) differed by at most 5 mV at any knot. */
static const uint16_t curve_mv[] = {3400, 3456, 3490, 3520, 3538, 3564, 3591, 3640, 3680,
                                    3723, 3748, 3785, 3814, 3831, 3846, 3856, 3868, 3896,
                                    3945, 3981, 3996, 4003, 4007, 4010, 4016, 4036};
static const uint16_t curve_pm[] = {   0,   10,   20,   30,   40,   50,   60,   80,  100,
                                     125,  150,  200,  250,  300,  350,  400,  450,  500,
                                     550,  600,  650,  700,  750,  800,  850,  900};
#define CURVE_N (sizeof(curve_mv) / sizeof(curve_mv[0]))
_Static_assert(sizeof(curve_pm) == sizeof(curve_mv), "curve tables must pair");

/* Level in per mille, 0..900, for a pack voltage below the top clamp. */
static uint16_t curve(uint16_t mv) {
    if (mv <= curve_mv[0]) return 0;
    if (mv >= curve_mv[CURVE_N - 1]) return curve_pm[CURVE_N - 1];
    for (uint8_t i = 1; i < CURVE_N; i++) {
        if (mv < curve_mv[i]) {
            uint32_t span = curve_mv[i] - curve_mv[i - 1];
            uint32_t into = mv - curve_mv[i - 1];
            return (uint16_t)(curve_pm[i - 1] + (into * (uint32_t)(curve_pm[i] - curve_pm[i - 1])) / span);
        }
    }
    return curve_pm[CURVE_N - 1];
}

/* The level for a `5C` estimate below the top clamp; 0 at the bottom clamp. */
static uint16_t c5_level(uint16_t e) {
    return c5_bottom(e) ? 0u : curve(c5_to_mv(e));
}

#define LEVEL_UNKNOWN      0xFFFFu
#define LEVEL_FULL         1000u
/* Booted at the top clamp: the voltage says only "at least ~90% at full white"
 * (less under a light load), so take the level saved before the reboot (every
 * cable <-> BT slider flip is one): a 90-100% save point, or the below-band
 * marker, which restores as 89%. With nothing saved -- after a flash erased
 * it -- guess 95%. Below the clamp the voltage is the starting point and
 * nothing is restored. */
#define LEVEL_CLAMP_GUESS  950u
#define LEVEL_CLAMP_EXIT   900u
/* On battery the level moves down only after the curve has sat below it for
 * this many fresh estimates in a row (~15 s: the 09-29 post-flash walk stepped
 * 1% about every 15 s), then to the HIGHEST of them. Every move
 * outside the deliberate re-seat is at most 1%, so a correction (a countdown
 * that ran slow, a charge rising fast) eases instead of jumping. */
#define STEP_DOWN_MEDIANS  6u
#define STEP_MAX_PM        10u

static uint16_t level      = LEVEL_UNKNOWN;
static uint8_t  below_run  = 0;
static uint16_t below_best = 0;
static bool     full       = false;

/* What is saved, and when. ⚠️ Every internal-flash write blanks the whole LED
 * matrix for a few ms: the row ISR de-selects every row while the flash is in
 * its program state, because each per-line program window masks interrupts
 * (the vector table and the row ISR live in flash, and the M0 has no VTOR) and
 * a row left lit across one shows at ~18x (docs/leds.md). JD sees the blink;
 * 2026-09-29. Saving every whole-percent change was ~100
 * writes a discharge. The restore is only used at a clamped boot, so save in
 * the 90..100 band, in 2.5% steps, rounded DOWN so a restore never
 * overstates: FULL (on USB), then 97.5, 95, 92.5, 90 on battery, and one marker
 * below the band, which a clamped boot restores as itself, 89% (Phase 2: the
 * count runs below 90% while a light load keeps the pack clamped). Lossy: a
 * stale marker after a partial charge or a pack swap reads up to ~9 low until
 * the count and the voltage meet (codex, Phase 2 verify 2; reboots are outside
 * the gauge's accuracy target). Six writes a charge cycle; nothing while
 * charging. */
#define LEVEL_SAVE_BELOW_BAND 890u

static uint16_t level_save_point(void) {
    if (level >= LEVEL_FULL) return LEVEL_FULL;
    if (level >= LEVEL_CLAMP_EXIT) return (uint16_t)((level / 25u) * 25u);
    return LEVEL_SAVE_BELOW_BAND;
}

static void level_save_tick(void) {   /* 1 Hz */
    if (level == LEVEL_UNKNOWN) return;
    if (full || supply == BATTERY_SUPPLY_BATTERY) kb_eeconfig_set_batt_level(level_save_point());
}

static uint16_t level_at_clamp_boot(void) {
    uint16_t saved;
    /* Phase 2: the count runs on through the clamp (a light load stays
     * clamped below 90% true), so the below-band marker is a real answer --
     * "under 90%" -- and restores as itself, not as the 95% guess (codex,
     * verify: a count at 80% came back as 95 after a reboot). */
    if (kb_eeconfig_get_batt_level(&saved) && saved >= LEVEL_SAVE_BELOW_BAND) return saved;
    return LEVEL_CLAMP_GUESS;
}

static void level_toward(uint16_t target) {
    if (target > level) {
        level = (target - level > STEP_MAX_PM) ? (uint16_t)(level + STEP_MAX_PM) : target;
    } else if (target < level) {
        level = (level - target > STEP_MAX_PM) ? (uint16_t)(level - STEP_MAX_PM) : target;
    }
}

/* LED drive, per mille of the maximum, over the last second: the committed
 * frames' time-weighted mean (sn32f2xx_led_drive_take), which is after the
 * power cap -- the real drive. */
#define LED_LOAD_MAX ((uint32_t)RGB_MATRIX_LED_COUNT * 3u * 255u)
static uint16_t led_pm = 0;
uint16_t battery_led_pm(void) { return led_pm; }

/* --- The energy count (Phase 2; plans/PHASE2-BUILD-PLAN.md, section 1) ---------
 * On the flat stretches of the curve a few mV are ~10 points (R3, 10-18: the
 * level read up to 13.8 low at 70-80% against the logged energy), so on
 * battery the level is COUNTED: the board's draw, modelled from what it knows
 * it is doing, integrated over elapsed time and taken off the level, 1 pm per
 * E_PM_NJ. The voltage only bounds it, by a band: the curve at both ends of
 * `5C`'s allowance (BAND_MV_UP, BAND_MV_DOWN), widened by BAND_PM. Above the band the ratchet
 * pulls the level down to its top; below it the level holds and the count's
 * pending energy is dropped (no debt to drain later). It never rises on
 * battery but at the re-seat. Where the curve is steep the band is narrow and
 * the voltage leads; on the flat stretches it is wide and the count leads.
 *
 * THE MODEL (R1's per-load map, 10-15, at ~4.17 V; the board is a
 * constant-power load, 305-311 mW over R3's whole drain): calibrated for JD's
 * unit as it runs (the MCU awake, BT linked, the panel drawing), USB data
 * attached or not. Not measured: the radio's other states, 2.4G, temperature,
 * another unit. All in uW.
 *   base     the floor with every light out, less USB data (R2's 7.1 mW)
 *   USB      while USB is configured on battery: only the bench does that
 *   backlight linear in its duty: 39.1 mW at duty 48/48
 *   RGB      the committed frames' drive, time-weighted
 *            (sn32f2xx_led_drive_take): A while any LED is lit, plus B per
 *            unit of each colour's channel sum. Linear in drive (QMK's CIE
 *            curve made it look otherwise in values: 64 and 128 are drives of
 *            12 and 48). PER COLOUR (the 10-19 map,
 *            history/power-bench-2026-10-15/rgb-curve-20261019/,
 *            scripts/rgb_fit.py): red draws 1.29x the mean per unit, green
 *            0.90, blue 0.81; one B for all read red 7.7% low and blue 7.2%
 *            high, the fit is within 0.6% at every step, and purple, outside
 *            it, within 0.2%. A is the fit's 7.71 mW against the measured
 *            RGB-off, refitted against this model's own (0.93 mW lower).
 *            The B's are per unit over RGB_MATRIX_LED_COUNT's 81 LEDs. Until
 *            10-21 the fit counted 82 (rgb_fit.py's N), so they were 81/82 of
 *            these (3636/2533/2294) and the RGB read ~1.2% low; A is
 *            unchanged (plans/BACKLOG.md, "The RGB model's 82 LEDs"). */
#define P_BASE_UW        106900u
#define P_USB_UW           7100u
#define P_BKL_FULL_UW     39100u
#define P_RGB_A_UW         8640u
#define P_RGB_R_NW         3681u   /* nW per unit of the red channels' sum (81 channels) */
#define P_RGB_G_NW         2565u   /* ... green */
#define P_RGB_B_NW         2322u   /* ... blue */
#define BKL_DUTY_FULL        48u
/* The capacity: R3's 15,579 mWh from FULL to the RGB cut, at JD's settings
 * (history/battery-2026-10-15-drain-2f/, "A1/A2"). One pm is a thousandth:
 * 15,579 mWh * 3.6e9 nJ/mWh / 1000. */
#ifndef E_CAP_MWH   /* overridable so scripts/battery_sim can replay a wrong capacity */
#    define E_CAP_MWH    15579u
#endif
#define E_PM_NJ          ((uint64_t)E_CAP_MWH * 3600000u)   /* uW.ms per pm */
#define NJ_PER_MWH_X10   360000000u                          /* 0.1 mWh in uW.ms */
/* The band, asymmetric. The upper edge (the ratchet) is the curve BAND_MV_UP
 * above the estimate: `5C`'s own ~10 mV, plus how far the pack's plateau
 * moved between cycles -- on R3 `5C` read 10-25 mV below the curve's voltage
 * for the logged energy, so 12 mV ratcheted a right count down by 11 points
 * (the firmware replay, scripts/battery_sim c_replay_r3). The lower edge (the
 * hold) is wider still: the pack's voltage RISES when the load falls (R1:
 * +10 mV from 73 to 28 mA), so with the ladder an idle board reads high, and
 * a tight lower edge would pause the count through every idle night -- the
 * level then high, the dangerous direction. It is a guard against a grossly
 * over-counting model, not a correction. BAND_PM absorbs the estimate's
 * noise. */
#define BAND_MV_UP        BATTERY_BAND_MV_UP
#define BAND_MV_DOWN      BATTERY_BAND_MV_DOWN
#define BAND_PM           BATTERY_BAND_PM
/* The count alone never takes the level below 1%: 0% is the protection's cut
 * (protection_tick sets it when the cut latches). */
#define COUNT_FLOOR_PM    10u

static uint64_t e_used_nj   = 0;   /* modelled energy from the pack since FULL; never held */
static uint64_t e_period_nj = 0;   /* the same, this log period's */
static uint64_t e_minute_nj = 0;   /* this minute's, for the average */
static uint64_t count_nj    = 0;   /* not yet taken off the level */
static uint32_t e_last_ms   = 0;
static bool     e_started   = false;
static bool     band_hold   = false;   /* below the band: the level waits */
static uint32_t p_now_uw    = 0;       /* the last second's mean draw */
static uint8_t  count_state = 0;       /* BATTERY_COUNT_* for HC_POWER */

/* The average draw, for time left: each minute's mean on battery, into a mean
 * over the minutes so far, which becomes an exponential average with a 12 h
 * time constant once there are 720 of them (an early minute cannot bias a
 * whole drain, codex). Frozen on USB. */
#define AVG_MAX_MINUTES  720u
static int32_t  p_avg_uw     = 0;
static uint16_t avg_minutes  = 0;
static uint32_t minute_ms    = 0;
static uint16_t left_min     = 0xFFFFu;   /* to the cut, minutes; 0xFFFF none */

static int32_t band_lower(uint16_t mv) {
    int32_t lo = (int32_t)curve((uint16_t)(mv - BAND_MV_DOWN)) - BAND_PM;
    return lo < 0 ? 0 : lo;
}
static int32_t band_upper(uint16_t mv) {
    /* An allowance reaching past the curve's top knot reaches the clamp, where
     * the curve says only "at least 90%": no bound (codex: 900 + 15 there
     * ratcheted a right count down from 4011 mV up). */
    if ((uint32_t)mv + BAND_MV_UP >= curve_mv[CURVE_N - 1]) return (int32_t)LEVEL_FULL;
    int32_t hi = (int32_t)curve((uint16_t)(mv + BAND_MV_UP)) + BAND_PM;
    return hi > (int32_t)LEVEL_FULL ? (int32_t)LEVEL_FULL : hi;
}

/* A level on battery: 0 only from the protection's cut, which is authoritative;
 * otherwise never under the count's 1% floor (codex: a boot at 3424 mV read
 * 0% above the cut). */
static uint16_t battery_floor(uint16_t lv) {
    if (power_lights_cut()) return 0;
    return lv < COUNT_FLOOR_PM ? COUNT_FLOOR_PM : lv;
}

/* The re-seat's and the handover's rule for a known level against a relaxed
 * estimate below the clamp: kept inside the band, else to its nearer edge. */
static uint16_t band_clamp(uint16_t lv, uint16_t mv) {
    int32_t lo = band_lower(mv), hi = band_upper(mv);
    if ((int32_t)lv < lo) return (uint16_t)lo;
    if ((int32_t)lv > hi) return (uint16_t)hi;
    return lv;
}

static void count_rebase(void) {
    count_nj = 0;
}

/* FULL: the count starts over. */
static void energy_full(void) {
    e_used_nj = 0;
    count_nj  = 0;
    band_hold = false;
}

/* The model's energy over `dt` ms, given each colour's drive sum x ms over it
 * and the ms any LED was lit: the RGB's intercept only for the lit time (codex). */
static uint64_t model_nj(uint32_t dt, const uint64_t rgb_ms[3], uint32_t lit_ms) {
    uint64_t uw = P_BASE_UW + (uint64_t)P_BKL_FULL_UW * display_backlight_duty() / BKL_DUTY_FULL;
    if (battery_usb_configured()) uw += P_USB_UW;
    uint64_t e = uw * dt;
    e += (uint64_t)P_RGB_A_UW * (lit_ms < dt ? lit_ms : dt) +
         (rgb_ms[0] * P_RGB_R_NW + rgb_ms[1] * P_RGB_G_NW + rgb_ms[2] * P_RGB_B_NW) / 1000u;
    return e;
}

/* Energy `e` off the level's count, on battery, given the estimate `est` (its
 * clamp state). The awake count and the sleep's term (battery_sleep_account)
 * both take theirs here. */
static void count_take(uint64_t e, uint16_t est) {
    if (power_lights_cut()) {
        /* The cut's latch is authoritative: 0, whatever is owed. */
        level       = 0;
        reseat      = false;
        count_state = BATTERY_COUNT_CUT;
        count_nj    = 0;
    } else if (level != LEVEL_UNKNOWN && !reseat) {
        /* At the top clamp nothing bounds the count: the clamp's 90% holds
         * only at full white, and lighter loads (the ladder) stay clamped
         * lower, so the old countdown's 90.5% floor would hold a level up and
         * drop its energy (codex). */
        bool clamp = c5_top(est);
        if (band_hold && !clamp) {
            count_state = BATTERY_COUNT_HELD;
            count_nj    = 0;   /* dropped, not banked */
        } else {
            count_state = clamp ? BATTERY_COUNT_CLAMP : BATTERY_COUNT_RUN;
            count_nj += e;
            while (count_nj >= E_PM_NJ && level > COUNT_FLOOR_PM) {
                count_nj -= E_PM_NJ;
                level--;
            }
            if (level <= COUNT_FLOOR_PM) count_nj = 0;
        }
    } else if (reseat && level != LEVEL_UNKNOWN) {
        /* Relaxing after an unplug: the level is the charging model's, and it
         * still pays for what the board draws meanwhile (codex: ~1 point at
         * 306 mW over RELAX_S). The re-seat bounds the result. */
        count_state = BATTERY_COUNT_RELAX;
        count_nj += e;
        while (count_nj >= E_PM_NJ && level > COUNT_FLOOR_PM) {
            count_nj -= E_PM_NJ;
            level--;
        }
    }
}

/* Time left from the level and the awake average: hours of USE, since the
 * average never sees slept time (QMK's timer stands still asleep, and the
 * sleep's energy goes to the count alone). */
static void time_left_update(void) {
    if (level != LEVEL_UNKNOWN && level > 0 && p_avg_uw > 0) {
        uint64_t ms = ((uint64_t)level * E_PM_NJ) / (uint32_t)p_avg_uw;
        uint64_t mn = ms / 60000u;
        left_min    = mn > 0xFFFEu ? 0xFFFEu : (uint16_t)mn;
    } else {
        left_min = 0xFFFFu;
    }
}

/* Once a second, on the elapsed time: the count, the period's energy, the
 * average. The LED drive is taken every call, on USB too, so a battery
 * second never inherits a USB stretch's frames. */
static void energy_tick(void) {
    uint32_t now      = timer_read32();
    uint32_t lit_ms   = 0;
    uint64_t rgb_ms[3];
    uint64_t drive_ms = sn32f2xx_led_drive_take(now, &lit_ms, rgb_ms);
    if (!e_started) {
        e_started = true;
        e_last_ms = now;
        return;
    }
    uint32_t dt = now - e_last_ms;
    e_last_ms   = now;
    if (dt) led_pm = (uint16_t)((drive_ms * 1000u) / ((uint64_t)LED_LOAD_MAX * dt));
    if (supply != BATTERY_SUPPLY_BATTERY || dt == 0) {
        count_state = BATTERY_COUNT_OFF;
        left_min    = 0xFFFFu;
        minute_ms   = 0;
        e_minute_nj = 0;
        return;
    }
    uint64_t e = model_nj(dt, rgb_ms, lit_ms);
    p_now_uw   = (uint32_t)(e / dt);
    e_used_nj += e;
    e_period_nj += e;
    e_minute_nj += e;

    uint16_t est = battery_5c_x100();
    if (est == C5_EST_NONE) band_hold = false;   /* no fresh evidence, no hold (codex) */
    count_take(e, est);

    minute_ms += dt;
    if (minute_ms >= 60000u) {
        int32_t p = (int32_t)(e_minute_nj / minute_ms);
        if (avg_minutes < AVG_MAX_MINUTES) avg_minutes++;
        p_avg_uw += (p - p_avg_uw) / (int32_t)avg_minutes;
        minute_ms   = 0;
        e_minute_nj = 0;
        time_left_update();
    }
}

uint32_t battery_power_uw(void)     { return p_now_uw; }
uint32_t battery_power_avg_uw(void) { return p_avg_uw > 0 ? (uint32_t)p_avg_uw : 0u; }
uint16_t battery_avg_minutes(void)  { return avg_minutes; }
uint16_t battery_time_left_min(void) {
    if (supply != BATTERY_SUPPLY_BATTERY || level == LEVEL_UNKNOWN || level == 0 || power_lights_cut())
        return 0xFFFFu;
    return left_min;
}
uint32_t battery_energy_used_mwh_x10(void) { return (uint32_t)(e_used_nj / NJ_PER_MWH_X10); }
uint8_t  battery_count_state(void) { return count_state; }
int16_t  battery_band_lower(void) {
    uint16_t m = battery_5c_x100();
    return (m == C5_EST_NONE || c5_top(m)) ? -1 : (int16_t)band_lower(c5_to_mv(m));
}
int16_t  battery_band_upper(void) {
    uint16_t m = battery_5c_x100();
    return (m == C5_EST_NONE || c5_top(m)) ? -1 : (int16_t)band_upper(c5_to_mv(m));
}

/* --- Charging: the model (Phase 1b, B; plans/BATTERY-GAUGE-REFINE-PLAN.md) ------
 * While charging, `5C` reads the TERMINAL voltage, which the charge current
 * lifts above the pack's own, and no constant I*R maps it onto the discharge
 * curve (its 4.00-4.02 V plateau has no counterpart on charge). So the level
 * comes from an EMPIRICAL model of a charge from JD's Mac through the ASC4056,
 * BT position -- an estimate for that stated condition, not a measurement --
 * bounded by the voltage:
 *
 *   M = L0 + K_CC t                    linear, until it reaches L_KNEE
 *   M = the tail table (battery_tail.h) from L_KNEE, on its own clock: a
 *       decelerating approach that starts at K_CC and reaches 990 exactly
 *       T_TAIL after the knee. A start above the knee joins the tail at its
 *       own level.
 *
 * The displayed level, each second, by precedence: it never falls; it never
 * rises past the evidence (a fresh estimate below the clamp bounds it by
 * U = curve(estimate); at the clamp there is no voltage bound; with no fresh
 * estimate it does not rise); it rises at most RISE_PM_PER_S; it never exceeds
 * 990 before FULL. U overstates under charge -- a ceiling, never a target.
 *
 * LOST ("Charge") when the model contradicts the voltage: (a) M - U > LOST_PM
 * for LOST_S of accumulated fresh below-clamp seconds (the clamp and missing
 * estimates hold the timer, they do not reset it), (b) no fresh estimate for
 * STALE_LOST_S, or (c) OVERRUN, T_OVERRUN of charging after the tail clock
 * reaches T_TAIL without FULL. All of it per mille, integer, once a second. */
/* The constants are battery.h's (BATTERY_*), so the simulator tests the
 * values the firmware ships. */
#define LEVEL_MODEL_CAP  BATTERY_MODEL_CAP
#define LOST_PM          BATTERY_LOST_PM
#define LOST_S           BATTERY_LOST_S
#define STALE_LOST_S     BATTERY_STALE_LOST_S
#define RISE_PM_PER_S    BATTERY_RISE_PM_PER_S
#define T_OVERRUN_S      BATTERY_T_OVERRUN_S
#define RELAX_S          BATTERY_RELAX_S
#define PAUSE_S          BATTERY_PAUSE_S
#define FLAT_X100        BATTERY_FLAT_X100
_Static_assert(PAUSE_S >= RELAX_S, "a handover must not come before the relaxation");
_Static_assert(BATT_L_KNEE_PM < LEVEL_MODEL_CAP, "the knee is below the cap");

/* The charging state (the log v5 chg byte's bits 0-2). */
enum { CHG_NONE = 0, CHG_UNKNOWN, CHG_FROM_FLAT, CHG_MODEL, CHG_LOST, CHG_FULL };
/* The chg byte's latched bits, OR-ed over a log period. */
#define CHG_F_LOST      0x08u   /* LOST entered, by (a) or (b) */
#define CHG_F_OVERRUN   0x10u   /* LOST entered by (c) */
#define CHG_F_HANDOVER  0x20u   /* a pause handed the level back */
#define CHG_F_SELFCHECK 0x40u   /* a rise ended above the then-fresh U: never expected */
#define CHG_F_SATURATED 0x80u   /* the period's report sum or count saturated */

static uint8_t  chg_st     = CHG_NONE;
/* The model is running: opened by CHRG low for SESSION_TICKS continuously (at
 * a boot or after a handover), closed at FULL, at unplug, or by a handover.
 * Kept apart from `session`, which means only "a re-seat is owed at unplug". */
static bool     modeled    = false;
static bool     boot_session_done = false;   /* FROM-FLAT is the boot's first session only */
static bool     m_top_up   = false;   /* opened above the cap: a full pack topping up keeps 1000 */
static uint16_t m_l0       = 0;
static uint32_t m_lin_s    = 0;       /* charging seconds in the linear phase */
static bool     m_in_tail  = false;
static uint32_t t_tail     = 0;       /* the tail clock; keeps counting past T_TAIL, for OVERRUN */
static uint16_t m_pm       = 0;       /* M, whole pm (half up) */
static uint16_t lost_a_s   = 0, stale_s = 0, pause_s = 0;
static uint8_t  chg_latch  = 0;
/* The boot's first estimate, taken on USB before any time on the pack. */
static uint16_t boot_first_x100  = 0xFFFFu;
static bool     boot_first_taken = false;
/* A handover's held number, not yet adopted or re-seated from a relaxed
 * estimate: shown, but no start for a session (chg_open). */
static bool     level_held       = false;

/* FROM-FLAT's input: the boot's first estimate, on USB, before any time on
 * the pack. Latched once, from battery_5c_report at the fifth report. The
 * FIRST, whatever the supply then: one taken before the supply is known, or
 * on the pack, makes this no flat boot on USB, and no later estimate becomes
 * the first (codex, gate 7's verification). On USB the supply resolves within
 * EXT_ENTER_TICKS, long before the module's fifth report. */
static void boot_first_latch(uint16_t est) {
    if (boot_first_taken) return;
    boot_first_taken = true;
    boot_first_x100  = (supply == BATTERY_SUPPLY_EXTERNAL && !ran_from_pack) ? est : 0xFFFFu;
}
/* Relaxation: at an unplug owing a re-seat, or a pause's stop, the ring is
 * emptied once more RELAX_S later, so the next estimate is built only from
 * reports received at least that long after. */
static bool     relax_pending = false, relax_done = false;
static uint32_t relax_from    = 0;
/* After a handover the idle path adopts a level once, from a relaxed estimate. */
static bool     adopt_owed    = false;

/* FROM-FLAT's test on the boot's first estimate (exported for the simulator). */
bool battery_first_estimate_is_flat(uint16_t first_x100) {
    return first_x100 != C5_EST_NONE && first_x100 <= FLAT_X100;
}

static void relax_start(void) {
    relax_pending = true;
    relax_done    = false;
    relax_from    = timer_read32();
}

static void relax_cancel(void) {
    relax_pending = false;
    relax_done    = false;
}

static void relax_task(void) {   /* 10 Hz */
    if (relax_pending && timer_elapsed32(relax_from) >= RELAX_S * 1000u) {
        relax_pending = false;
        relax_done    = true;
        c5_forget();   /* the next estimate: reports from RELAX_S on */
    }
}

/* M on the tail clock, in 1/16 pm: nodes a minute apart, linear between them
 * (integer floor); the index saturates, so past T_TAIL it is exactly 990 * 16. */
static uint32_t tail_x16(uint32_t s) {
    uint32_t i = s / 60u;
    if (i >= BATT_TAIL_N) return batt_tail_x16[BATT_TAIL_N];
    uint32_t f = s - i * 60u;
    return batt_tail_x16[i] + ((uint32_t)(batt_tail_x16[i + 1] - batt_tail_x16[i]) * f) / 60u;
}

/* The first tail-clock second whose M is >= l0, in X16 units: a node search,
 * then an integer ceiling inside the segment. */
static uint32_t tail_entry_s(uint16_t l0) {
    uint32_t target = (uint32_t)l0 * 16u;
    for (uint32_t i = 0; i < BATT_TAIL_N; i++) {
        if (batt_tail_x16[i + 1] >= target) {
            if (batt_tail_x16[i] >= target) return i * 60u;
            uint32_t d = batt_tail_x16[i + 1] - batt_tail_x16[i];
            return i * 60u + ((target - batt_tail_x16[i]) * 60u + d - 1u) / d;
        }
    }
    return BATT_TAIL_N * 60u;
}

static void model_set_from_tail(void) {
    m_pm = (uint16_t)((tail_x16(t_tail) + 8u) / 16u);
}

static void model_start(uint16_t l0) {
    m_l0    = (l0 > LEVEL_MODEL_CAP) ? LEVEL_MODEL_CAP : l0;
    m_lin_s = 0;
    if (m_l0 >= BATT_L_KNEE_PM) {
        m_in_tail = true;
        t_tail    = tail_entry_s(m_l0);
        model_set_from_tail();
    } else {
        m_in_tail = false;
        t_tail    = 0;
        m_pm      = m_l0;
    }
}

/* One second of charging. */
static void model_advance(void) {
    if (!m_in_tail) {
        m_lin_s++;
        uint32_t m = m_l0 + (BATT_K_CC_PM_PER_H * m_lin_s) / 3600u;
        if (m < BATT_L_KNEE_PM) {
            m_pm = (uint16_t)m;
            return;
        }
        m_in_tail = true;
        t_tail    = 0;
    } else if (t_tail < UINT32_MAX) {
        t_tail++;
    }
    model_set_from_tail();
}

/* A real charging session opens the model. */
static void chg_open(void) {
    /* A handover still waiting for its relaxed estimate adopted nothing: the
     * number it holds is the closed session's display, not a start (codex,
     * gate 7). The plan: MODEL from the adopted level, or UNKNOWN-CHG. An
     * unplug in between does not make it one either (its verification). */
    bool unadopted = adopt_owed || level_held;
    level_held     = false;
    modeled  = true;
    m_top_up = false;
    lost_a_s = stale_s = pause_s = 0;
    adopt_owed = false;
    relax_cancel();
    if (unadopted) {
        level  = LEVEL_UNKNOWN;
        chg_st = CHG_UNKNOWN;
    } else if (level != LEVEL_UNKNOWN) {
        chg_st   = CHG_MODEL;
        m_top_up = level > LEVEL_MODEL_CAP;   /* a 100 kept through a top-up (just full) */
        model_start(level);
    } else if (!boot_session_done && !ran_from_pack && battery_first_estimate_is_flat(boot_first_x100)) {
        chg_st = CHG_FROM_FLAT;
        level  = 0;
        model_start(0);
    } else {
        chg_st = CHG_UNKNOWN;   /* "Charge": no trusted start */
    }
    boot_session_done = true;
}

static void chg_close(uint8_t st) {
    modeled = false;
    chg_st  = st;
}

/* A pause of PAUSE_S: the charger is idle or faulted; nothing to model. */
static void chg_handover(void) {
    chg_latch |= CHG_F_HANDOVER;
    if (chg_st == CHG_LOST || chg_st == CHG_UNKNOWN) level = LEVEL_UNKNOWN;
    chg_close(CHG_NONE);
    adopt_owed = true;   /* relax_task has run from the stop: the next estimate is relaxed */
    level_held = true;   /* until adopt_relaxed: the display, not a start */
}

static void chg_lost(uint8_t why) {
    chg_latch |= why;
    chg_st = CHG_LOST;
    level  = LEVEL_UNKNOWN;   /* "Charge"; re-seats as UNKNOWN at unplug */
}

/* Once a second while the model is open. */
static void chg_tick_1hz(void) {
    if (!modeled) return;
    if (!charging_now()) {   /* a pause: M and every timer stop, the display holds */
        if (pause_s == 0) relax_start();
        if (pause_s < UINT16_MAX) pause_s++;
        if (pause_s >= PAUSE_S) chg_handover();
        return;
    }
    if (pause_s) {
        pause_s = 0;
        relax_cancel();
    }
    if (chg_st != CHG_MODEL && chg_st != CHG_FROM_FLAT) return;   /* UNKNOWN or LOST: "Charge" */

    model_advance();
    uint16_t e     = battery_5c_x100();
    bool     fresh = e != C5_EST_NONE;
    bool     below = fresh && !c5_top(e);
    uint16_t u     = below ? c5_level(e) : 0u;
    uint16_t bound = !fresh ? level : below ? u : LEVEL_MODEL_CAP;
    uint16_t cand  = m_pm < LEVEL_MODEL_CAP ? m_pm : LEVEL_MODEL_CAP;
    if (cand > bound) cand = bound;
    if (cand > level) {
        uint16_t up = (uint16_t)(level + RISE_PM_PER_S);
        uint16_t nl = cand < up ? cand : up;
        if (below && nl > u) chg_latch |= CHG_F_SELFCHECK;
        level = nl;
    }
    if (m_top_up) return;   /* LOST never applies to a full pack topping up */

    if (below) lost_a_s = (m_pm > u + LOST_PM) ? (uint16_t)(lost_a_s + 1u) : 0u;   /* else it holds */
    stale_s = fresh ? 0u : (uint16_t)(stale_s < UINT16_MAX ? stale_s + 1u : stale_s);
    if (lost_a_s >= LOST_S || stale_s >= STALE_LOST_S) {
        chg_lost(CHG_F_LOST);
    } else if (m_in_tail && t_tail >= BATT_T_TAIL_S + T_OVERRUN_S) {
        chg_lost(CHG_F_OVERRUN);
    }
}

/* The re-seat at unplug and the handover's adoption share one rule, for a
 * relaxed estimate. An unknown level takes the curve (or, at the clamp, the
 * clamp's guess). A known one -- the charging model's, counted down since the
 * unplug -- is kept inside the band, else moved to its nearer edge; at the
 * clamp it is kept (Phase 2: the clamp is no bound under a light load). On
 * battery the result keeps the 1% floor, and the cut's 0 wins. */
static void adopt_relaxed(uint16_t m) {
    if (c5_top(m)) {
        if (level == LEVEL_UNKNOWN) level = LEVEL_CLAMP_GUESS;
    } else if (level == LEVEL_UNKNOWN || c5_bottom(m)) {
        level = c5_level(m);
    } else {
        /* Phase 2: a known level -- the charging model's, counted down since
         * the unplug -- is kept inside the band, else moved to its nearer
         * edge. Adopting the curve outright put the plateau's error back. */
        level = band_clamp(level, c5_to_mv(m));
    }
    if (supply == BATTERY_SUPPLY_BATTERY) level = battery_floor(level);
    count_rebase();
    band_hold = false;
    relax_done = false;
    level_held = false;
}

static uint8_t chg_state_now(void) {
    if (modeled) return chg_st;
    return full ? CHG_FULL : CHG_NONE;
}

static void full_tick(void) {
    bool was = full;
    full = supply == BATTERY_SUPPLY_EXTERNAL && chrg_off_run >= FULL_SETTLE_TICKS &&
           c5_top(battery_5c_x100());
    if (full && !was) energy_full();
}

/* One new fresh estimate, in hundredths of a count. */
static void level_report(uint16_t m) {
    if (supply == BATTERY_SUPPLY_BATTERY) {
        if (power_lights_cut()) {   /* the cut's 0 is authoritative (codex) */
            level     = 0;
            reseat    = false;
            below_run = 0;
            return;
        }
        if (reseat) {
            /* The re-seat after a real charge: owed from the unplug, resolved
             * by the first estimate built only from reports received RELAX_S
             * after it (relax_task empties the ring then). Until then, hold:
             * the pack is still relaxing from the charge current. A LOST or
             * UNKNOWN session left the level unknown, and re-seats as such. */
            below_run = 0;
            if (!relax_done) return;
            adopt_relaxed(m);
            reseat = false;
            return;
        }
        if (c5_top(m)) {
            /* The top clamp: the count (energy_tick) owns it, from wherever
             * charging left the level, with no bound from the voltage. */
            if (level == LEVEL_UNKNOWN) level = level_at_clamp_boot();
            below_run = 0;
            band_hold = false;
            return;
        }
        if (level == LEVEL_UNKNOWN) {   /* the first reading on the pack */
            level = battery_floor(c5_level(m));
            count_rebase();
            return;
        }
        uint16_t mv     = c5_to_mv(m);
        int32_t  upper  = band_upper(mv);
        band_hold       = (int32_t)level < band_lower(mv);
        if ((int32_t)level <= upper) {   /* inside, or below and waiting */
            below_run = 0;
            return;
        }
        /* Above the band: the ratchet, down to its top. */
        uint16_t target = upper < (int32_t)COUNT_FLOOR_PM ? COUNT_FLOOR_PM : (uint16_t)upper;
        if (below_run == 0 || target > below_best) below_best = target;
        if (++below_run < STEP_DOWN_MEDIANS) return;
        below_run = 0;
        level_toward(below_best);
        count_rebase();
        return;
    }
    below_run = 0;
    if (supply != BATTERY_SUPPLY_EXTERNAL) return;   /* UNKNOWN: touch nothing */

    if (full) {
        level      = LEVEL_FULL;
        level_held = false;
        return;
    }
    /* Charging, or paused inside a modeled session: the model owns the level
     * (chg_tick_1hz). Charging before a session qualifies moves nothing -- a
     * brief plug-in cannot bump the level, and a boot on USB charging shows
     * "Charge" until its first session opens. */
    if (modeled || charging_now()) return;
    /* On USB, the charger idle or faulted. After a handover, adopt once from a
     * relaxed estimate; until then, hold. */
    if (adopt_owed) {
        if (!relax_done) return;
        adopt_relaxed(m);
        adopt_owed = false;
        return;
    }
    if (c5_top(m)) {
        if (level == LEVEL_UNKNOWN) level = level_at_clamp_boot();
        return;
    }
    uint16_t target = c5_level(m);
    if (level == LEVEL_UNKNOWN) {
        level = target;
        return;
    }
    /* Below the clamp, the charger idle: the pack is neither charging nor
     * discharging, so a known level stays, bounded by the band. Walking it to
     * the curve put the plateau's error back after every handover (codex). */
    level_toward(band_clamp(level, c5_to_mv(m)));
}

/* Supply changes (supply_tick). An unplug closes the model; after a real
 * session it owes the re-seat, which waits RELAX_S. A replug before the
 * re-seat resolves keeps it owed, and its RELAX_S restarts at the next
 * unplug. */
static void supply_changed(battery_supply_t was) {
    if (was == BATTERY_SUPPLY_EXTERNAL && supply == BATTERY_SUPPLY_BATTERY) {
        if (modeled) chg_close(CHG_NONE);
        adopt_owed = false;
        /* Every known level enters battery operation floored, or zeroed by a
         * latched cut: a level adopted on USB (a boot at 3424 mV adopts 4 pm),
         * a cut lifted by a brief replug, or a low charging model would
         * otherwise show 0% above the cut on the pack (codex, verify). */
        if (level != LEVEL_UNKNOWN) level = battery_floor(level);
        if (session) reseat = true;
        /* Owed from an earlier unplug too: a brief replug in between (no new
         * session, so `session` stays clear) restarts RELAX_S here. */
        if (reseat) relax_start();
    } else if (supply == BATTERY_SUPPLY_EXTERNAL) {
        relax_cancel();
    }
}

uint16_t battery_level_permille(void) { return level; }

